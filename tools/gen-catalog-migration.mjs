#!/usr/bin/env node
// Writes the capsule catalog migration from a capsules.json export of Bartesian's Shopify
// catalog (design/capsules.json by default). It's an upsert, so a later catalog refresh is a
// new migration from the same script, never an edit to an applied one:
//
//   npm run gen:catalog                                  -> 007_capsules_catalog.sql
//   npm run gen:catalog -- path/to/capsules.json supabase/migrations/0NN_catalog_refresh.sql
//
// Multi-cocktail products are skipped: a variety pack isn't one capsule you can pour.

import { readFileSync, writeFileSync } from "node:fs";

const [input = "design/capsules.json", output = "supabase/migrations/007_capsules_catalog.sql"] =
  process.argv.slice(2);

const SPIRITS = new Set(["vodka", "tequila", "whiskey", "rum", "gin", "multi"]);
const NOT_A_SINGLE_COCKTAIL = /variety pack|collection|advent/i;

const raw = JSON.parse(readFileSync(input, "utf8"));
const skipped = raw.filter((c) => NOT_A_SINGLE_COCKTAIL.test(c.name));
const capsules = raw.filter((c) => !NOT_A_SINGLE_COCKTAIL.test(c.name));

for (const c of capsules) {
  if (!c.id || !c.name || !c.img || !c.img2) throw new Error(`incomplete capsule: ${c.id}`);
  if (!SPIRITS.has(c.spirit)) throw new Error(`unknown spirit "${c.spirit}" on ${c.id}`);
}

const sql = (v) => (v == null || v === "" ? "NULL" : `'${String(v).replaceAll("'", "''")}'`);

const rows = capsules.map(
  (c, i) =>
    `  (${sql(c.id)}, ${sql(c.name)}, ${sql(c.spirit)}, ${sql(c.img)}, ${sql(c.img2)}, ${sql(c.desc)}, ${i + 1})`,
);

const out = `---------------------------------------------------------------------------------------------
-- Bartesian single-cocktail catalog: ${capsules.length} capsules. Generated by
-- tools/gen-catalog-migration.mjs from ${input}; don't hand-edit, regenerate.
${skipped.length ? `-- Skipped (not a single cocktail): ${skipped.map((c) => c.name).join(", ")}\n` : ""}
INSERT INTO capsules (id, name, spirit, img_box, img_pour, description, sort_order) VALUES
${rows.join(",\n")}
ON CONFLICT (id) DO UPDATE SET
  name = EXCLUDED.name,
  spirit = EXCLUDED.spirit,
  img_box = EXCLUDED.img_box,
  img_pour = EXCLUDED.img_pour,
  description = EXCLUDED.description,
  sort_order = EXCLUDED.sort_order;
`;

writeFileSync(output, out);
console.log(`gen-catalog: ${capsules.length} capsules -> ${output}`);
if (skipped.length) console.log(`gen-catalog: skipped ${skipped.map((c) => c.name).join(", ")}`);
