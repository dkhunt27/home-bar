#!/usr/bin/env node
// Writes the collections migration from supabase/catalog/collections.json, a hand-curated
// snapshot of Bartesian's variety packs (Shopify doesn't list a pack's contents as data, only
// in its description). Like gen-catalog-migration.mjs it's an upsert, so a refresh (next
// year's holiday packs) is a new migration from the same script, never an edit to an applied
// one:
//
//   npm run gen:collections                     -> 018_collections_catalog.sql
//   npm run gen:collections -- supabase/migrations/0NN_collections_refresh.sql
//
// "cocktails" are the ones that only come in a collection. They become capsules with
// sold_single = false and borrow their photos from the collection named in "from" (Bartesian
// doesn't shoot them alone); "img2" overrides the pour photo when there's a better one.

import { readFileSync, writeFileSync } from "node:fs";

const [output = "supabase/migrations/018_collections_catalog.sql"] = process.argv.slice(2);
const INPUT = "supabase/catalog/collections.json";
const SINGLES = "design/capsules.json";

const SPIRITS = new Set(["vodka", "tequila", "whiskey", "rum", "gin", "multi"]);
// After the single-cocktail catalog's sort_order (1..54), so catalog order keeps singles first.
const SORT_ORDER_BASE = 1000;

const { cocktails, collections } = JSON.parse(readFileSync(INPUT, "utf8"));
const singles = new Set(JSON.parse(readFileSync(SINGLES, "utf8")).map((c) => c.id));
const collectionById = new Map(collections.map((c) => [c.id, c]));
const cocktailIds = new Set(cocktails.map((c) => c.id));

for (const c of cocktails) {
  if (!c.id || !c.name || !c.desc) throw new Error(`incomplete cocktail: ${c.id}`);
  if (!SPIRITS.has(c.spirit)) throw new Error(`unknown spirit "${c.spirit}" on ${c.id}`);
  if (singles.has(c.id)) throw new Error(`${c.id} is already a single; list it in items only`);
  const from = collectionById.get(c.from);
  if (!from) throw new Error(`${c.id}: "from" names no collection (${c.from})`);
  if (!from.items[c.id]) throw new Error(`${c.id}: not in its "from" collection ${c.from}`);
}
for (const col of collections) {
  if (!col.id || !col.name || !col.img) throw new Error(`incomplete collection: ${col.id}`);
  const items = Object.entries(col.items ?? {});
  if (items.length === 0) throw new Error(`${col.id} has no items`);
  for (const [id, qty] of items) {
    if (!singles.has(id) && !cocktailIds.has(id)) throw new Error(`${col.id}: unknown ${id}`);
    if (!Number.isInteger(qty) || qty < 1) throw new Error(`${col.id}: bad qty for ${id}`);
  }
}
const unused = cocktails.filter((c) => !collections.some((col) => col.items[c.id]));
if (unused.length) throw new Error(`in no collection: ${unused.map((c) => c.id).join(", ")}`);

const sql = (v) => (v == null || v === "" ? "NULL" : `'${String(v).replaceAll("'", "''")}'`);

const cocktailRows = cocktails.map((c, i) => {
  const from = collectionById.get(c.from);
  const pour = c.img2 ?? from.img2 ?? from.img;
  return `  (${sql(c.id)}, ${sql(c.name)}, ${sql(c.spirit)}, ${sql(from.img)}, ${sql(pour)}, ${sql(c.desc)}, ${SORT_ORDER_BASE + i + 1}, false)`;
});
const collectionRows = collections.map(
  (col, i) => `  (${sql(col.id)}, ${sql(col.name)}, ${sql(col.img)}, ${i + 1})`,
);
const itemRows = collections.flatMap((col) =>
  Object.entries(col.items).map(([id, qty]) => `  (${sql(col.id)}, ${sql(id)}, ${qty})`),
);

const out = `---------------------------------------------------------------------------------------------
-- Bartesian collections: ${collections.length} variety packs, plus ${cocktails.length} cocktails that only come in one.
-- Generated by tools/gen-collections-migration.mjs from ${INPUT};
-- don't hand-edit, regenerate.

INSERT INTO capsules (id, name, spirit, img_box, img_pour, description, sort_order, sold_single) VALUES
${cocktailRows.join(",\n")}
ON CONFLICT (id) DO UPDATE SET
  name = EXCLUDED.name,
  spirit = EXCLUDED.spirit,
  img_box = EXCLUDED.img_box,
  img_pour = EXCLUDED.img_pour,
  description = EXCLUDED.description,
  sort_order = EXCLUDED.sort_order,
  sold_single = EXCLUDED.sold_single;

INSERT INTO collections (id, name, img, sort_order) VALUES
${collectionRows.join(",\n")}
ON CONFLICT (id) DO UPDATE SET
  name = EXCLUDED.name,
  img = EXCLUDED.img,
  sort_order = EXCLUDED.sort_order;

-- Contents are replaced wholesale, so a refresh can also drop a flavor from a pack.
DELETE FROM collection_items WHERE collection_id IN (
${collections.map((col) => `  ${sql(col.id)}`).join(",\n")}
);

INSERT INTO collection_items (collection_id, capsule_id, qty) VALUES
${itemRows.join(",\n")};
`;

writeFileSync(output, out);
console.log(
  `gen-collections: ${collections.length} collections, ${cocktails.length} collection-only cocktails -> ${output}`,
);
